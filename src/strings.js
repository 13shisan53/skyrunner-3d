export const STRINGS = Object.freeze({ 'zh-CN': zh, en });
export const LOCALES = ['zh-CN', 'en'];

let current = 'zh-CN';

export function setLocale(locale) {
  current = LOCALES.includes(locale) ? locale : 'zh-CN';
  return current;
}

export function getLocale() {
  return current;
}

export function detectLocale() {
  try {
    const lang = (navigator.language || '').toLowerCase();
    return lang.startsWith('zh') ? 'zh-CN' : 'en';
  } catch {
    return 'zh-CN';
  }
}

export function t(key, vars) {
  const table = STRINGS[current] || STRINGS['zh-CN'];
  let text = table[key];
  if (text === undefined) text = STRINGS['zh-CN'][key];
  if (text === undefined) return key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] === undefined ? m : String(vars[name])));
}
